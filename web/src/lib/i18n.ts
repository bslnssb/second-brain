const DICTS: Record<Lang, Dict> = { zh: ZH, en: EN, es: ES, pt: PT, hi: HI }

function detect(): Lang {
  // ?lang=en 强制指定语言（README 里写的快捷方式、给朋友发的链接都靠它）。
  // 优先级最高：这是一次性的显式要求，比「用户存过偏好」更明确。
  try {
    const forced = (new URLSearchParams(location.search).get('lang') || '').toLowerCase()
    if (forced && DICTS[forced as Lang]) return forced as Lang
  } catch {
    /* 非浏览器环境（测试）没有 location，忽略 */
  }
  // 只有**用户在设置里主动选过**（sb_lang_user=1）才认 localStorage。
  // 早先版本的测试/脚本往这个键里写过 en，结果中文系统的用户一进来就是英文——
  // 光看 sb_lang 分不清「用户选的」还是「别人写进去的」。
  const chosen = localStorage.getItem('sb_lang_user') === '1'
  const saved = (localStorage.getItem('sb_lang') || '').toLowerCase()
  if (chosen && saved && DICTS[saved as Lang]) return saved as Lang
  const nav = (navigator.language || 'zh').toLowerCase()
  if (nav.startsWith('zh')) return 'zh'
  if (nav.startsWith('es')) return 'es'
  if (nav.startsWith('pt')) return 'pt'
  if (nav.startsWith('hi')) return 'hi'
  if (nav.startsWith('en')) return 'en'
  return 'zh'
}

let LANG: Lang = detect()

export function getLang(): Lang {
  return LANG
}

export function t(key: string): string {
  // 长文案只翻了 中/英/西/葡；印地语缺的键回落到英文，比掉回中文好读
  return DICTS[LANG][key] ?? DICTS.en[key] ?? ZH[key] ?? key
}

export function setLang(l: Lang, user = false) {
  LANG = l
  localStorage.setItem('sb_lang', l)
  if (user) localStorage.setItem('sb_lang_user', '1')
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : l
  window.dispatchEvent(new Event('sb-lang'))
}
